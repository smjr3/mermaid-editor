const known = new Set<string>(flowShapeNames);

/** The shape's short name, from any name mermaid accepts for it; undefined if none. */
export const canonicalShape = (name: string): FlowShapeName | undefined => {
  const key = name.trim().toLowerCase();
  return known.has(key) ? (key as FlowShapeName) : aliases[key];
};
